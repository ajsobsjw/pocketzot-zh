/** Dungeon features: altars, stairs, gates, walls and the like. */
export function featureName(plain: string): string | null {
  const altar = /^(?:A|An|The)\s+.*?altar of (.+)$/i.exec(plain)
  if (altar) {
    const god = GOD_ZH[altar[1]] ?? GOD_ZH[altar[1].replace(/^an? /, '')]
    return god ? `${god}的祭坛` : null
  }
  const stair = /^(?:A|An)\s+(.*?)staircase(.*)$/i.exec(plain)
  if (stair) {
    const material = /stone|metal|slimy|sand-covered/i.exec(stair[1])?.[0].toLowerCase() ?? ''
    const matZh = material ? (ADJ_ZH[material] ?? '') : ''
    const tail = stair[2].trim()
    const back = /^back to (.+)$/i.exec(tail)
    if (back) return `回到${PLACE_ZH[back[1]] ?? back[1]}的${matZh}楼梯`
    const to = /^to (.+)$/i.exec(tail)
    if (to) return `通往${PLACE_ZH[to[1]] ?? to[1]}的${matZh}楼梯`
    if (/leading down/i.test(tail)) return `向下的${matZh}楼梯`
    if (/leading up/i.test(tail)) return `向上的${matZh}楼梯`
    if (/out of the dungeon/i.test(tail)) return `离开地牢的${matZh}楼梯`
    return `${matZh}楼梯`
  }
  const gateway = /^(?:A|An)\s+gateway (?:leading )?(back )?(?:in)?to (.+)$/i.exec(plain)
  if (gateway) {
    const place = PLACE_ZH[gateway[2]] ?? gateway[2]
    return gateway[1] ? `回到${place}的传送门` : `通往${place}的传送门`
  }
  const gate = /^(?:A|An)\s+(?:one-way )?gate (?:leading )?(?:out of|to) (.+)$/i.exec(plain)
  if (gate) return `通往${PLACE_ZH[gate[1]] ?? gate[1]}的大门`
  const door = /^(?:A|An)\s+(.*?)\b(door|gate)$/i.exec(plain)
  if (door) {
    const words = door[1].trim().split(/\s+/).filter(Boolean)
    const zh = words.map((w) => ADJ_ZH[w.toLowerCase()] ?? DOC_ADJ[w.toLowerCase()] ?? '').join('')
    return `${zh}${door[2].toLowerCase() === 'gate' ? '大门' : '门'}`
  }
  const wall = /^(?:A|An|The)\s+(.+?)wall$/i.exec(plain)
  if (wall) {
    const words = wall[1].trim()
      .replace(/highly decorated/i, '装饰精美的')
      .split(/\s+/)
    const zh = words.map((w) => ADJ_ZH[w.toLowerCase()] ?? w).join('')
    return `${zh}墙`
  }
  return FEATURE_ZH[plain] ?? null
}
