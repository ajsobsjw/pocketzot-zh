/** Translate a single HUD status pill (`s.light`), preserving numbers/signs. */
export function translateStatusLight(raw: string): string {
  if (!isZh() || !raw) return raw
  const trimmed = raw.trim()
  if (STATUS_LIGHT_ZH[trimmed]) return STATUS_LIGHT_ZH[trimmed]

  const param = /^(Corr|Regen|MPRegen|Flay|Fugue|Gem|Horr|Memories|Enkindled|Phobia|Shield|Torch|Zot)\s*\(([^)]+)\)$/.exec(trimmed)
  if (param) {
    const names: Record<string, string> = {
      Corr: '腐蚀',
      Regen: '再生',
      MPRegen: '回魔',
      Flay: '剥皮',
      Fugue: '赋格',
      Gem: '宝石',
      Horr: '恐惧',
      Memories: '记忆',
      Enkindled: '燃魂',
      Phobia: '恐慌',
      Shield: '护盾',
      Torch: '火把',
      Zot: '佐特',
    }
    return `${names[param[1]]} (${param[2]})`
  }
  const slay = /^Slay ([+-]\d+)$/.exec(trimmed)
  if (slay) return `杀戮 ${slay[1]}`
  const ray = /^(Ray|Wave)(\+*)$/.exec(trimmed)
  if (ray) return `${ray[1] === 'Ray' ? '射线' : '波动'}${ray[2]}`
  const prog = /^(Blast|Winding)(\.*)$/.exec(trimmed)
  if (prog) return `${prog[1] === 'Blast' ? '爆轰' : '蓄能'}${prog[2]}`
  return raw
}

/** Translate a status pill tooltip (`s.text`). */
export function translateStatusTooltip(text: string): string {
  if (!isZh() || !text) return text
  return t(text)
}

