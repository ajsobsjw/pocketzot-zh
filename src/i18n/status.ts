/** Translate one monster-panel status word from monsterStatusLabels(). */
export function translateMonsterPanelStatus(word: string): string {
  if (!isZh() || !word) return word
  const hit = MONSTER_PANEL_STATUS_ZH[word.toLowerCase()]
  if (hit) return hit
  const mem = /^(\d+) memor(?:y|ies) left$/.exec(word)
  if (mem) return `剩余 ${mem[1]} 点记忆`
  return word
}
